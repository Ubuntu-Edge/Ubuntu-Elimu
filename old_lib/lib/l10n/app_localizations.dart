class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();
  
  @override
  bool isSupported(Locale locale) {
    return AppLocales.supportedLocales
        .any((l) => l.languageCode == locale.languageCode);
  }
  
  @override
  Future<AppLocalizations> load(Locale locale) async {
    return AppLocalizations(locale);
  }
  
  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

/// LocaleProvider manages the app's locale state
class LocaleProvider extends ChangeNotifier {
  static const String _localeKey = 'app_locale';
  
  Locale _locale = AppLocales.english;
  
  Locale get locale => _locale;
  
  /// Alias for locale to be used in MaterialApp
  Locale get currentLocale => _locale;
  
  LocaleProvider() {
    _loadSavedLocale();
  }
  
  Future<void> _loadSavedLocale() async {
    final prefs = await SharedPreferences.getInstance();
    final localeCode = prefs.getString(_localeKey);
    
    if (localeCode != null) {
      final parts = localeCode.split('_');
      if (parts.length >= 2) {
        _locale = Locale(parts[0], parts[1]);
        notifyListeners();
      }
    }
  }
  
  Future<void> setLocale(Locale locale) async {
    if (!AppLocales.supportedLocales.any((l) => l.languageCode == locale.languageCode)) {
      return;
    }
    
    _locale = locale;
    
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_localeKey, '${locale.languageCode}_${locale.countryCode}');
    
    notifyListeners();
  }
  
  void clearLocale() async {
    _locale = AppLocales.english;
    
    final prefs = await SharedPreferences.getInstance();
    await prefs.remove(_localeKey);
    
    notifyListeners();
  }
}
