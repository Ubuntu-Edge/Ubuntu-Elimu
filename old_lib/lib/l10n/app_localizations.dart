  static String getLanguageName(Locale locale) {
    switch (locale.languageCode) {
      case 'en':
        return 'English';
      case 'sw':
        return 'Kiswahili';
      case 'fr':
        return 'Français';
      case 'pt':
        return 'Português';
      case 'am':
        return 'አማርኛ';
      default:
        return 'Unknown';
    }
  }
  
  static String getLocaleName(Locale locale) {
    switch (locale.languageCode) {
      case 'en':
        return 'English (US)';
      case 'sw':
        return 'Kiswahili (Kenya)';
      case 'fr':
        return 'Français (France)';
      case 'pt':
        return 'Português (Moçambique)';
      case 'am':
        return 'አማርኛ (Ethiopia)';
      default:
        return 'Unknown';
    }
  }
}

