import 'dart:async';
import '../models/offline_context_params.dart';

class OfflineAiService {
  bool _isInitialized = false;
  bool get isInitialized => _isInitialized;

  // This will be replaced by the actual native binding (e.g., llama_cpp_dart)
  Future<void> initialize(String modelPath) async {
    // Simulate model loading
    await Future.delayed(const Duration(seconds: 2));
    _isInitialized = true;
  }

  Future<void> dispose() async {
    _isInitialized = false;
  }

  Stream<String> generateResponse(
    String prompt, {
    OfflineContextParams params = const OfflineContextParams(),
  }) async* {
    if (!_isInitialized) {
      throw Exception('Model not initialized. Call initialize() first.');
    }

    // Mock streaming response for now
    final mockResponse = "This is a simulated offline AI response to: \"$prompt\". In a real implementation, this would be generated by a local LLM like Phi-3 or Llama-3 running on your device.";
    
    final words = mockResponse.split(' ');
    for (var word in words) {
      await Future.delayed(const Duration(milliseconds: 50));
      yield '$word ';
    }
  }

  Future<String> generateSummary(String text) async {
    // Placeholder for summarization logic
    return "Summary: $text".substring(0, 100) + "...";
  }
}
